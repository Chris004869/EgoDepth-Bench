"""Export Table II (main), Table V (views) and Table VI (adaptation).

Every cell is read from a result document written by `score.scorer`. Nothing is
retyped and nothing is computed a second time here.

MISSING IS RENDERED AS MISSING. A method with no result gets `\\pending`; a site
set with reference but no predictions gets `NA` with its coverage still shown. An
empty CSV or a zero is never used to stand in for "not run" -- that is the whole
point of separating `abs_rel is None` from `abs_rel == 0` upstream.

Development exports carry a `[development]` marker in the caption so a draft
cannot be mistaken for a formal result.
"""

