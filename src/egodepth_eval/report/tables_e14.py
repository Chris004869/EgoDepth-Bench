def load_results(results_dir: Path) -> dict:
    """Every result document in a directory, keyed by method name."""
    results: dict = {}
    for path in sorted(Path(results_dir).glob("*.json")):
        try:
            payload = json.loads(path.read_text())
        except (OSError, json.JSONDecodeError):
            continue
        if isinstance(payload, dict) and payload.get("method"):
            results[payload["method"]] = payload
    return results


def stratum(result: dict, key: str) -> dict:
    return (result or {}).get("strata", {}).get(key, {})


def metric(result: dict, stratum_key: str, name: str, available: bool = False):
    """One metric, or None. `available` reads the available-site variant."""
    block = stratum(result, stratum_key)
    source = "available_site_metrics" if available else "metrics"
    return block.get(source, {}).get(name)


def format_number(value, digits: int = 3, scale: float = 1.0, missing: str = PENDING) -> str:
    if value is None:
        return missing
    return f"{float(value) * scale:.{digits}f}"


def format_percent(value, digits: int = 1, missing: str = PENDING) -> str:
    if value is None:
        return missing
    return f"{100.0 * float(value):.{digits}f}"


def _macro_or_na(result: dict, stratum_key: str, name: str, digits: int, scale: float) -> str:
    """Complete macro when defined; otherwise NA with the available-site value.

    This is where "a site produced nothing" becomes visible in the table instead
    of being averaged away.
    """
    block = stratum(result, stratum_key)
    if not block:
        return PENDING
    value = block.get("metrics", {}).get(name)
    if value is not None:
        return format_number(value, digits, scale)
    fallback = block.get("available_site_metrics", {}).get(name)
    if fallback is None:
        return PENDING
    return f"{NOT_AVAILABLE} ({format_number(fallback, digits, scale)})"


def generate_main_table(
    results: dict, output_path: Path, status: str = "development"
) -> Path:
    """Table II: whole-image on the main test set, hand/object on the subset."""
    marker = "" if status == "formal" else f" [{status}]"
    lines = [
        r"% Generated by egodepth_eval.report.tables_e14 -- do not edit by hand.",
        rf"% status: {status}",
        r"\begin{table*}[t]",
        rf"  \caption{{Public-checkpoint evaluation on unseen sites, with equal site",
        r"  weights. Whole-image scores use the main test set; hand and object scores",
        r"  use the annotated subset. ROI cells report MAE$_Z$ (cm) / coverage (\%).",
        r"  Coverage counts valid predictions within reference support $G$. A site with",
        r"  reference but no predictions makes the complete macro-average undefined;",
        rf"  such cells read NA with the available-site value in brackets.{marker}}}",
        r"  \label{tab:main_results}",
        r"  \centering",
        r"  \footnotesize",
        r"  \setlength{\tabcolsep}{3pt}",
        r"  \begin{tabular*}{\textwidth}{@{\extracolsep{\fill}}lccccccc@{}}",
        r"    \toprule",
        r"    & & \multicolumn{4}{c}{Main test set: whole image}",
        r"      & \multicolumn{2}{c}{Annotated subset} \\",
        r"    \cmidrule(lr){3-6}\cmidrule(l){7-8}",
        r"    Method & Views & AbsRel$\downarrow$",
        r"      & \shortstack{MAE$_Z$\\(cm)$\downarrow$}",
        r"      & $\delta_1\uparrow$ & \shortstack{Coverage\\(\%)$\uparrow$}",
        r"      & \shortstack{Hand\\MAE$_Z\downarrow$/Cov.$\uparrow$}",
        r"      & \shortstack{Object\\MAE$_Z\downarrow$/Cov.$\uparrow$} \\",
        r"    \midrule",
    ]

    for group_index, (header, rows) in enumerate(MAIN_TABLE_GROUPS):
        if any(row[0] == 'mapanything_6view' for row in rows) and 'mapanything_6view_rig' in results:
            rows = [*rows, ('mapanything_6view_rig', 'MapAnything + rig poses', 6)]
        if group_index:
            lines.append(r"    \midrule")
        lines.append(rf"    \multicolumn{{8}}{{l}}{{{header}}} \\")
        for method, display, n_views in rows:
            result = results.get(method)
            cells = [
                _macro_or_na(result, "roi::full", "abs_rel", 3, 1.0),
                _macro_or_na(result, "roi::full", "mae_z_cm", 2, 1.0),
                _macro_or_na(result, "roi::full", "delta_1", 3, 1.0),
                format_percent(metric(result, "roi::full", "coverage")),
                (
                    _macro_or_na(result, "roi::hand", "mae_z_cm", 2, 1.0)
                    + "/"
                    + format_percent(metric(result, "roi::hand", "coverage"))
                ),
                (
                    _macro_or_na(result, "roi::object", "mae_z_cm", 2, 1.0)
                    + "/"
                    + format_percent(metric(result, "roi::object", "coverage"))
                ),
            ]
            lines.append(
                f"    {display} & {n_views} & " + " & ".join(cells) + r" \\"
            )

    lines += [
        r"    \bottomrule",
        r"  \end{tabular*}",
        r"\end{table*}",
    ]
    Path(output_path).parent.mkdir(parents=True, exist_ok=True)
    Path(output_path).write_text("\n".join(lines) + "\n")
    return Path(output_path)


def generate_views_table(
    results: dict,
    output_path: Path,
    cost: Optional[dict] = None,
    status: str = "development",
) -> Path:
    """Table V: one MapAnything checkpoint at 1, 2 and 6 views, plus cost."""
    marker = "" if status == "formal" else f" [{status}]"
    methods = ["mapanything_1view", "mapanything_2view", "mapanything_6view"]
    if 'mapanything_6view_rig' in results:
        methods.append('mapanything_6view_rig')
    cost = cost or {}

    def row(label: str, stratum_key: str, name: str, digits: int, percent: bool = False):
        cells = []
        for method in methods:
            result = results.get(method)
            if percent:
                cells.append(format_percent(metric(result, stratum_key, name), digits))
            else:
                cells.append(_macro_or_na(result, stratum_key, name, digits, 1.0))
        return f"    {label} & " + " & ".join(cells) + r" \\"

    def cost_row(label: str, key: str, digits: int, scale: float = 1.0):
        cells = []
        for method in methods:
            value = (cost.get(method) or {}).get(key)
            cells.append(PENDING if value is None else f"{float(value) * scale:.{digits}f}")
        return f"    {label} & " + " & ".join(cells) + r" \\"

    lines = [
        r"% Generated by egodepth_eval.report.tables_e14 -- do not edit by hand.",
        rf"% status: {status}",
        r"\begin{table}[t]",
        r"  \caption{Additional views for a fixed MapAnything checkpoint: camera~2,",
        r"  cameras~2/3, or all six cameras, each with its own calibrated rays.",
        r"  Scores use unaligned metric $Z$; object rows use the annotated subset.",
        r"  Optional multi-view confidence filtering is disabled. Runtime and peak",
        rf"  memory are per call on the hardware named in the run record.{marker}}}",
        r"  \label{tab:view_ablation}",
        r"  \centering",
        r"  \footnotesize",
        r"  \setlength{\tabcolsep}{3pt}",
        r"  \begin{tabular*}{\columnwidth}{@{\extracolsep{\fill}}lccc@{}}",
        r"    \toprule",
        r"    Evaluation & 1 view & 2 views & 6 views \\",
        r"    \midrule",
        r"    \multicolumn{4}{l}{\textit{Main test set: whole image}} \\",
        row(r"AbsRel$\downarrow$", "roi::full", "abs_rel", 3),
        row(r"MAE$_Z$ (cm)$\downarrow$", "roi::full", "mae_z_cm", 2),
        row(r"Coverage (\%)$\uparrow$", "roi::full", "coverage", 1, percent=True),
        r"    \midrule",
        r"    \multicolumn{4}{l}{\textit{Annotated subset}} \\",
        row(r"Object MAE$_Z$ (cm)$\downarrow$", "roi::object", "mae_z_cm", 2),
        row(r"Object $A_{5\mathrm{cm}}$ (\%)$\uparrow$", "roi::object", "a_5cm", 1, percent=True),
        row(r"Object coverage (\%)$\uparrow$", "roi::object", "coverage", 1, percent=True),
        r"    \midrule",
        cost_row(r"Time (ms)$\downarrow$", "median_ms", 0),
        cost_row(r"Memory (GB)$\downarrow$", "peak_gpu_gb", 1),
        r"    \bottomrule",
        r"  \end{tabular*}",
        r"\end{table}",
    ]
    if len(methods) == 4:
        lines = [line.replace(r'\fill}}lccc@{}', r'\fill}}lcccc@{}')
                 .replace(r'\multicolumn{4}', r'\multicolumn{5}')
                 .replace(r'Evaluation & 1 view & 2 views & 6 views \\',
                          r'Evaluation & 1 view & 2 views & 6 views & 6 + rig \\')
                 for line in lines]
        lines.insert(5, r'  The 6 + rig condition additionally receives known metric camera-to-rig poses.')
    Path(output_path).parent.mkdir(parents=True, exist_ok=True)
    Path(output_path).write_text("\n".join(lines) + "\n")
    return Path(output_path)


def generate_adaptation_table(
    results: dict,
    output_path: Path,
    aligned: Optional[dict] = None,
    status: str = "development",
    methods: Optional[list] = None,
) -> Path:
    """Table VI: Public / Scale-only / Fine-tuned, plus the shared-support diagnostic."""
    marker = "" if status == "formal" else f" [{status}]"
    methods = methods or ["mapanything_6view", "mapanything_scale_only", "mapanything_ft"]
    aligned = aligned or {}

    def row(label: str, stratum_key: str, name: str, digits: int, percent: bool = False):
        cells = []
        for method in methods:
            result = results.get(method)
            if percent:
                cells.append(format_percent(metric(result, stratum_key, name), digits))
            else:
                cells.append(_macro_or_na(result, stratum_key, name, digits, 1.0))
        return f"    {label} & " + " & ".join(cells) + r" \\"

    def aligned_row(label: str, key: str, digits: int):
        cells = []
        for method in methods:
            value = (aligned.get(method) or {}).get(key)
            cells.append(PENDING if value is None else f"{float(value):.{digits}f}")
        return f"    {label} & " + " & ".join(cells) + r" \\"

    lines = [
        r"% Generated by egodepth_eval.report.tables_e14 -- do not edit by hand.",
        rf"% status: {status}",
        r"\begin{table}[t]",
        r"  \caption{MapAnything adaptation on unseen sites with six RGB views and",
        r"  calibrated rays. Scale-only freezes the network and fits one positive",
        r"  multiplier on a fixed training subset with the same log-Huber objective;",
        r"  the fine-tuned column is direct metric output and is not multiplied by it.",
        r"  ROI rows use the annotated subset. The last two rows fit one positive",
        r"  scale per output on full-frame",
        r"  $G\cap P_{\mathrm{public}}\cap P_{\mathrm{fine\text{-}tuned}}$ and reuse it",
        rf"  for object scoring.{marker}}}",
        r"  \label{tab:adaptation}",
        r"  \centering",
        r"  \footnotesize",
        r"  \setlength{\tabcolsep}{2pt}",
        r"  \begin{tabular*}{\columnwidth}{@{\extracolsep{\fill}}lccc@{}}",
        r"    \toprule",
        r"    Evaluation & Public & Scale-only & Fine-tuned \\",
        r"    \midrule",
        r"    \multicolumn{4}{l}{\textit{Main test set: whole image}} \\",
        row(r"AbsRel$\downarrow$", "roi::full", "abs_rel", 3),
        row(r"MAE$_Z$ (cm)$\downarrow$", "roi::full", "mae_z_cm", 2),
        row(r"Coverage (\%)$\uparrow$", "roi::full", "coverage", 1, percent=True),
        r"    \midrule",
        r"    \multicolumn{4}{l}{\textit{Annotated subset}} \\",
        row(r"Hand MAE$_Z$ (cm)$\downarrow$", "roi::hand", "mae_z_cm", 2),
        row(r"Hand coverage (\%)$\uparrow$", "roi::hand", "coverage", 1, percent=True),
        row(r"Object MAE$_Z$ (cm)$\downarrow$", "roi::object", "mae_z_cm", 2),
        row(r"Object $A_{5\mathrm{cm}}$ (\%)$\uparrow$", "roi::object", "a_5cm", 1, percent=True),
        row(r"Object coverage (\%)$\uparrow$", "roi::object", "coverage", 1, percent=True),
        row(r"Active-object $A_{5\mathrm{cm}}$ (\%)$\uparrow$", "roi::active_object",
            "a_5cm", 1, percent=True),
        row(r"Active-object coverage (\%)$\uparrow$", "roi::active_object",
            "coverage", 1, percent=True),
        r"    \midrule",
        aligned_row(r"Aligned AbsRel$\downarrow$", "abs_rel", 3),
        aligned_row(r"Aligned object MAE$_Z$ (cm)$\downarrow$", "object_mae_z_cm", 2),
        r"    \bottomrule",
        r"  \end{tabular*}",
        r"\end{table}",
    ]
    if methods[0] == 'mapanything_6view_rig':
        lines = [line.replace('calibrated rays. Scale-only', 'calibrated rays and metric rig poses. Scale-only') for line in lines]
    Path(output_path).parent.mkdir(parents=True, exist_ok=True)
    Path(output_path).write_text("\n".join(lines) + "\n")
    return Path(output_path)


def export_support_csv(results: dict, output_path: Path) -> Path:
    """Per-method, per-ROI support: the counts behind every table cell.

    An 8-page paper cannot show these, but a reader who wants to know how many
    sites and pixels a number rests on needs them, and a table cell alone cannot
    say whether an ROI mean came from two sites or eight.
    """
    rows: list = []
    for method, result in sorted(results.items()):
        for key, block in sorted(result.get("strata", {}).items()):
            if not key.startswith("roi::"):
                continue
            metrics = block.get("metrics", {})
            support = block.get("support", {})
            rows.append({
                "method": method,
                "roi": key.split("::", 1)[1],
                "population": result.get("population", {}).get("name"),
                "status": result.get("population", {}).get("status"),
                "n_sites_total": support.get("n_sites_total"),
                "n_sites_with_predictions": support.get("n_sites_with_predictions"),
                "n_sites_no_predictions": support.get("n_sites_no_predictions"),
                "n_sites_not_applicable": support.get("n_sites_not_applicable"),
                "complete_macro_defined": block.get("complete_macro_defined"),
                "n_reference_px": metrics.get("n_reference"),
                "n_scored_px": metrics.get("n_scored"),
                "abs_rel": metrics.get("abs_rel"),
                "abs_rel_available_sites": block.get("available_site_metrics", {}).get("abs_rel"),
                "mae_z_cm": metrics.get("mae_z_cm"),
                "delta_1": metrics.get("delta_1"),
                "coverage": metrics.get("coverage"),
                "a_5cm": metrics.get("a_5cm"),
            })
    output_path = Path(output_path)
    output_path.parent.mkdir(parents=True, exist_ok=True)
    if not rows:
        # An empty CSV is not evidence that anything ran, so say so in the file.
        output_path.write_text("# no results found; nothing was scored\n")
        return output_path
    with output_path.open("w", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)
    return output_path
